// Exemplos de Operadores de Atribuição em JavaScript

// Operador de Atribuição Básico (=)
let a = 10;
console.log(`Valor inicial de a: ${a}`); 

//Operador de atribuicao de adição (+=)
a += 5;
console.log(`Após a operação a += 5, o valor de a é: ${a}`);

// Operador de atribuição de subtração (-=)
a -= 3;
console.log(`Após a operação a -= 3, o valor de a é: ${a}`);

// Operador de atribuição de multiplicação (*=)
a *= 2;
console.log(`Após a operação a *= 2, o valor de a é: ${a}`);

// Operador de atribuição de divisão (/=)
a /= 4;
console.log(`Após a operação a /= 4, o valor de a é: ${a}`);

// Operador de atribuição de módulo (%=)
a %= 4;
console.log(`Após a operação a %= 4, o valor de a é: ${a}`);

// Operador de atribuição de exponenciação (**=)
a **= 3;
console.log(`Após a operação a **= 3, o valor de a é: ${a}`);

// Anotações e dicas sobre essa matéria:
// 1. O operador de atribuição básico (=) é usado para atribuir um valor a uma variável.
// 2. Os operadores de atribuição combinam uma operação matemática com a atribuição, permitindo atualizar o valor da variável de forma concisa.
// 3. É importante entender a ordem das operações e como cada operador afeta o valor da variável.
